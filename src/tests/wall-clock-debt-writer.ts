/**
 * The writer behind `scripts/wall-clock-debt.ts` (which has the usage): it
 * writes `wall-clock-debt.ts` and `fixed-sleep-debt.ts` from the tree as it
 * is, and refuses to GROW either unless told this is the ship-time merge.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { readCalibration } from "./time-bound-calibration";
import {
  debtKey,
  parseDebt,
  parseSleepDebt,
  requiredDebt,
  runAudit,
  type Audit,
  serializeDebt,
  serializeSleepDebt,
} from "./wall-clock-audit";
import { ROOT } from "./wall-clock-corpus";
import { WALL_CLOCK_EXEMPT } from "./wall-clock-exempt";
import { WALL_CLOCK_SEED } from "./wall-clock-seed";

const DEBT = path.join(ROOT, "src/tests/wall-clock-debt.ts");
const SLEEP = path.join(ROOT, "src/tests/fixed-sleep-debt.ts");

const DEBT_HEADER = `/**
 * GENERATED by scripts/wall-clock-debt.ts — do not edit by hand.
 *
 * Wall-clock comparisons not yet routed through src/tests/time-bound.ts or
 * e2e/time-bound.ts ("raw"), routed assert-mode calls with no valid CI
 * calibration ("routed"), and audit seeds the detector cannot see ("seed").
 * Each is tagged with the fix lane that owns it. wall-clock-bounds.test.ts
 * holds the list both ways: every entry matches a member of the tree, every
 * member is in it, and its length equals the ceiling below — which only a
 * shrink may lower. The list ends when it is empty; the guard does not.
 */`;
const SLEEP_HEADER = `/**
 * GENERATED by scripts/wall-clock-debt.ts — do not edit by hand.
 *
 * Fixed sleeps: \`page.waitForTimeout(N)\` and \`new Promise(r => setTimeout(r, N))\`
 * with N >= 2 (files that use fake timers excluded). A sleep leaves only by
 * becoming event-driven, or a declared observation window (\`observeFor\`).
 * Held both ways by wall-clock-bounds.test.ts.
 */`;

/**
 * Regenerates (or checks) both debt lists; returns the exit code and prints
 * what changed. Run inside vitest by `scripts/wall-clock-debt.ts` (vitest's
 * own config loader is what derives the corpus, and it does not load under
 * a CommonJS TypeScript hook).
 */
export async function regenerate(opts: {
  write: boolean;
  acceptNew: boolean;
  audit?: Audit;
}): Promise<number> {
  const { write, acceptNew } = opts;
  const audit = opts.audit ?? (await runAudit());
  const req = requiredDebt(
    audit,
    WALL_CLOCK_EXEMPT,
    readCalibration(),
    WALL_CLOCK_SEED,
  );
  const tsvOf = (file: string, name: string) => {
    if (!existsSync(file)) return "";
    // The literal's body, unescaped the way the template literal would be.
    const text = readFileSync(file, "utf8");
    const open = text.indexOf(`${name} = \``);
    if (open === -1) return "";
    let body = "";
    for (let i = open + name.length + 4; i < text.length; i++) {
      const ch = text[i]!;
      if (ch === "\\") {
        body += text[++i] ?? "";
        continue;
      }
      if (ch === "`") break;
      body += ch;
    }
    return body;
  };
  const oldEntries = parseDebt(tsvOf(DEBT, "WALL_CLOCK_DEBT_TSV"));
  const oldDebt = new Set(oldEntries.map(debtKey));
  const oldSleep = new Set(
    parseSleepDebt(tsvOf(SLEEP, "FIXED_SLEEP_DEBT_TSV")).map(debtKey),
  );
  const newDebt = req.debt.filter((e) => !oldDebt.has(debtKey(e)));
  const newSleep = req.sleepDebt.filter((e) => !oldSleep.has(debtKey(e)));
  const gone =
    oldDebt.size - req.debt.filter((e) => oldDebt.has(debtKey(e))).length;
  const goneSleep =
    oldSleep.size -
    req.sleepDebt.filter((e) => oldSleep.has(debtKey(e))).length;
  console.log(
    `corpus: ${audit.files.length} files (vitest ${audit.vitest.entries.length}, setup ${audit.vitest.setupFiles.length}, e2e ${audit.e2e.listed.length}, support ${audit.support.modules.length})`,
  );
  console.log(
    `members: ${audit.comparisons.length} comparisons, ${audit.routed.length} routed, ${audit.sleeps.length} sleeps; debt ${req.debt.length} (was ${oldDebt.size}: ${newDebt.length} new, ${gone} gone), sleep debt ${req.sleepDebt.length} (was ${oldSleep.size}: ${newSleep.length} new, ${goneSleep} gone)`,
  );
  for (const e of newDebt)
    console.log(
      `  NEW debt  [${e.lane}] ${e.kind} ${e.file}#${e.n}: ${e.snippet}`,
    );
  for (const e of newSleep)
    console.log(`  NEW sleep [${e.lane}] ${e.file}#${e.n}: ${e.snippet}`);
  // A comparison ROUTED through the helper but not yet calibrated is a new
  // "routed" entry in place of the "raw" one it replaces — a conversion,
  // not growth — as long as its file lost at least as many entries.
  const wanted = new Set(req.debt.map(debtKey));
  const lostIn = (file: string) =>
    oldEntries.filter((e) => e.file === file && !wanted.has(debtKey(e))).length;
  const conversion = (file: string) =>
    newDebt.filter((e) => e.file === file).every((e) => e.kind === "routed") &&
    newDebt.filter((e) => e.file === file).length <= lostIn(file);
  const growth = newDebt.filter((e) => !conversion(e.file));
  if ((growth.length > 0 || newSleep.length > 0) && !acceptNew) {
    console.log(
      "The lists may only shrink. Route the new timing check through src/tests/time-bound.ts or e2e/time-bound.ts (measure mode first), or make the sleep event-driven. --accept-new is for the ship-time merge of main only.",
    );
    if (write) return 1;
  }
  const changed = newDebt.length + newSleep.length + gone + goneSleep > 0;
  if (!write) return changed ? 1 : 0;
  writeFileSync(DEBT, serializeDebt(req.debt, DEBT_HEADER));
  writeFileSync(SLEEP, serializeSleepDebt(req.sleepDebt, SLEEP_HEADER));
  console.log(
    `wrote ${path.relative(ROOT, DEBT)} (${req.debt.length}) and ${path.relative(ROOT, SLEEP)} (${req.sleepDebt.length})`,
  );
  return 0;
}
