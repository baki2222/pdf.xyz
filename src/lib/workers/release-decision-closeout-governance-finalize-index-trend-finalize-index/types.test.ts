import { describe, expect, it } from "vitest";
import {
  RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_CHECKLIST_DETAIL,
  RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_CHECKLIST_IDS,
  RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_EXIT,
  RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_EXIT_FOR_VERDICT,
  RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_REASON_DETAIL,
  RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_REASON_IDS,
  RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_SEVERITIES,
  RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_VERDICTS,
  RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_VERDICT_SUMMARY,
  releaseDecisionCloseoutGovernanceFinalizeIndexTrendFinalizeIndexExitCode,
} from "./types";
import { finalizedFinalize, makeIndex } from "./fixtures";

describe("closeout-governance-finalize-index vocabulary invariants", () => {
  it("verdict → exit is the documented ladder (invalid shares exit 4 with blocked)", () => {
    expect(RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_EXIT_FOR_VERDICT).toEqual({
      indexed: RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_EXIT.INDEXED,
      "index-open": RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_EXIT.OPEN,
      "index-incomplete": RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_EXIT.INCOMPLETE,
      "index-blocked": RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_EXIT.BLOCKED,
      "index-invalid": RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_EXIT.INVALID,
    });
    // exit values: indexed=0, usage=1, incomplete=2, open=3, blocked=4, invalid=4
    expect(RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_EXIT_FOR_VERDICT.indexed).toBe(0);
    expect(RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_EXIT_FOR_VERDICT["index-incomplete"]).toBe(2);
    expect(RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_EXIT_FOR_VERDICT["index-open"]).toBe(3);
    expect(RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_EXIT_FOR_VERDICT["index-blocked"]).toBe(4);
    expect(RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_EXIT_FOR_VERDICT["index-invalid"]).toBe(4);
    expect(RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_EXIT.USAGE).toBe(1);
  });

  it("the severity ladder puts invalid on top", () => {
    expect(RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_SEVERITIES).toEqual([
      "informational",
      "incomplete",
      "open",
      "blocking",
      "invalid",
    ]);
  });

  it("every verdict has an authored summary", () => {
    for (const v of RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_VERDICTS) {
      expect(RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_VERDICT_SUMMARY[v]).toBeTruthy();
    }
  });

  it("every reason id has an authored severity (in the ladder) + detail", () => {
    for (const id of RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_REASON_IDS) {
      const d = RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_REASON_DETAIL[id];
      expect(d.detail.length).toBeGreaterThan(20);
      expect(RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_SEVERITIES).toContain(d.severity);
    }
  });

  it("the invalid reasons are exactly the tampered + unreadable pair", () => {
    const invalidReasons = RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_REASON_IDS.filter(
      (id) => RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_REASON_DETAIL[id].severity === "invalid",
    );
    expect(invalidReasons.sort()).toEqual(["finalization-tampered", "finalization-unreadable"]);
  });

  it("every checklist id has an authored detail", () => {
    for (const id of RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_CHECKLIST_IDS) {
      expect(RELEASE_DECISION_CLOSEOUT_GOVERNANCE_FINALIZE_INDEX_TREND_FINALIZE_INDEX_CHECKLIST_DETAIL[id].length).toBeGreaterThan(20);
    }
  });

  it("releaseDecisionCloseoutGovernanceFinalizeIndexTrendFinalizeIndexExitCode reads the rollup exit", () => {
    expect(releaseDecisionCloseoutGovernanceFinalizeIndexTrendFinalizeIndexExitCode(makeIndex([finalizedFinalize()]))).toBe(0);
  });
});
