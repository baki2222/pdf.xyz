import { describe, expect, it } from "vitest";
import { newHandoffId } from "@/lib/handoff";
import { REDACTED, redactText, redactUrl, redactValue } from "./redact";

describe("redactText — handoff tokens", () => {
  it("strips a real handoff id generated by the store", () => {
    // Tie the assertion to the actual token format, not a hand-written guess.
    const id = newHandoffId();
    const out = redactText(`Failed to claim handoff ${id} on mount`);
    expect(out).not.toContain(id);
    expect(out).toContain("h_" + REDACTED);
  });

  it("strips a token hidden in a URL query string", () => {
    const out = redactText(
      "navigation to https://pdf.xyz/tools/merge-pdf?handoff=h_deadbeef1234 failed",
    );
    expect(out).not.toContain("h_deadbeef1234");
    // The URL survives only as origin + path; the query (and token) are gone.
    expect(out).toContain("https://pdf.xyz/tools/merge-pdf");
    expect(out).not.toContain("?handoff=");
  });

  it("redacts every token occurrence, not just the first", () => {
    const out = redactText("h_aaaa111 and again h_bbbb222 here");
    expect(out).not.toContain("h_aaaa111");
    expect(out).not.toContain("h_bbbb222");
  });
});

describe("redactText — file names", () => {
  it("redacts a bare filename but keeps the extension", () => {
    expect(redactText("could not open contract-final.pdf")).toBe(
      `could not open ${REDACTED}.pdf`,
    );
  });

  it("redacts a quoted filename that contains spaces", () => {
    const out = redactText('Error reading "Q3 Bank Statement.pdf" from disk');
    expect(out).not.toContain("Bank Statement");
    expect(out).not.toContain("Q3");
    expect(out).toContain(`"${REDACTED}.pdf"`);
  });

  it("covers common document and image extensions", () => {
    for (const name of [
      "report.docx",
      "sheet.XLSX",
      "slides.pptx",
      "scan.jpeg",
      "photo.PNG",
      "archive.zip",
    ]) {
      const out = redactText(`processing ${name}`);
      expect(out).not.toContain(name.split(".")[0]!);
    }
  });

  it("leaves code/asset paths (js/ts/css) untouched", () => {
    // These appear in stack traces and are safe (public bundle URLs, not docs).
    const stack = "at handler (/_next/static/chunks/main.js:12:5)";
    expect(redactText(stack)).toContain("main.js");
  });
});

describe("redactText — inline data + robustness", () => {
  it("strips data: and blob: URLs that could embed file bytes", () => {
    expect(redactText("src=data:application/pdf;base64,JVBERi0=")).toBe(
      `src=data:${REDACTED}`,
    );
    expect(redactText("blob:https://pdf.xyz/9f1c-uuid preview")).toContain(
      `blob:${REDACTED}`,
    );
  });

  it("is idempotent", () => {
    const once = redactText(
      'open "My File.pdf" from https://x.io/a?handoff=h_zzz',
    );
    expect(redactText(once)).toBe(once);
  });

  it("clips absurdly long input", () => {
    const out = redactText("x".repeat(5000));
    expect(out.length).toBeLessThanOrEqual(2048);
  });

  it("passes through empty / non-sensitive text", () => {
    expect(redactText("")).toBe("");
    expect(redactText("Something went wrong. Please try again.")).toBe(
      "Something went wrong. Please try again.",
    );
  });
});

describe("redactUrl", () => {
  it("keeps origin + pathname and drops query and hash", () => {
    expect(
      redactUrl("https://pdf.xyz/tools/merge-pdf?handoff=h_secrettoken#frag"),
    ).toBe("https://pdf.xyz/tools/merge-pdf");
  });

  it("scrubs a relative URL with a token", () => {
    const out = redactUrl("/tools/merge-pdf?handoff=h_abc123");
    expect(out).not.toContain("h_abc123");
    expect(out).not.toContain("?");
  });

  it("returns empty for empty input", () => {
    expect(redactUrl("")).toBe("");
  });
});

describe("redactValue — deep scrub", () => {
  it("drops known-sensitive keys entirely", () => {
    const out = redactValue({
      name: "Bank Statement.pdf",
      fileName: "secret.docx",
      files: ["a.pdf", "b.pdf"],
      token: "h_abc",
      content: "raw bytes here",
      count: 3,
    }) as Record<string, unknown>;
    expect(out.name).toBe(REDACTED);
    expect(out.fileName).toBe(REDACTED);
    expect(out.files).toBe(REDACTED);
    expect(out.token).toBe(REDACTED);
    expect(out.content).toBe(REDACTED);
    // Non-sensitive scalars pass through.
    expect(out.count).toBe(3);
  });

  it("reduces url-like keys to origin + path", () => {
    const out = redactValue({
      url: "https://pdf.xyz/tools/x?handoff=h_tok",
      href: "/workspace?handoff=h_tok2",
    }) as Record<string, string>;
    expect(out.url).toBe("https://pdf.xyz/tools/x");
    expect(out.href).not.toContain("h_tok2");
  });

  it("recursively scrubs nested strings and arrays", () => {
    const out = redactValue({
      detail: { note: "opened invoice.pdf" },
      list: ["ok", "see report.xlsx"],
    }) as { detail: { note: string }; list: string[] };
    expect(out.detail.note).toBe(`opened ${REDACTED}.pdf`);
    expect(out.list[1]).toBe(`see ${REDACTED}.xlsx`);
  });

  it("normalizes non-finite numbers and drops functions", () => {
    const out = redactValue({
      good: 42,
      nan: Number.NaN,
      inf: Number.POSITIVE_INFINITY,
      fn: () => 1,
    }) as Record<string, unknown>;
    expect(out.good).toBe(42);
    expect(out.nan).toBeNull();
    expect(out.inf).toBeNull();
    expect("fn" in out).toBe(false);
  });

  it("caps very large arrays", () => {
    const out = redactValue(
      Array.from({ length: 200 }, (_, i) => i),
    ) as unknown[];
    expect(out.length).toBeLessThanOrEqual(65);
    expect(String(out[out.length - 1])).toContain("more");
  });

  it("bounds recursion depth", () => {
    // Build a chain deeper than MAX_DEPTH.
    let deep: Record<string, unknown> = { v: "leaf" };
    for (let i = 0; i < 10; i++) deep = { next: deep };
    const out = redactValue(deep);
    expect(JSON.stringify(out)).toContain(REDACTED);
  });
});
