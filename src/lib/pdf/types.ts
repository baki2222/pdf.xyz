/**
 * Shared types for the client-side PDF engine. These are intentionally free of
 * any pdf-lib or DOM references so they can be imported from server components,
 * pure utilities, and tests alike.
 */

/** A page rotation in degrees. PDF rotation is always a multiple of 90. */
export type Rotation = 0 | 90 | 180 | 270;

/** An inclusive, 0-based range of pages. */
export interface PageRange {
  start: number;
  end: number;
}

/** One output document produced by splitting a PDF. */
export interface SplitPart {
  /** Suggested file name including extension, e.g. "report-pages-1-3.pdf". */
  name: string;
  /** 0-based page indices, in order, that make up this part. */
  indices: number[];
}

/**
 * A single entry in an "organize" plan. The plan is an ordered list, so its
 * order defines the output page order. `rotation` is the absolute orientation
 * to apply to the copied page (not a delta).
 */
export interface OrganizePlanItem {
  /** 0-based index into the source document. */
  sourceIndex: number;
  /** Absolute rotation to apply to the copied page. */
  rotation: Rotation;
  /**
   * Insert a new, empty page of this size (points, upright) here instead of
   * a copy of `sourceIndex`, which is then ignored.
   */
  blank?: { width: number; height: number };
}

/** Generated bytes paired with a suggested download filename. */
export interface NamedBytes {
  name: string;
  bytes: Uint8Array;
}
