/**
 * The field finder read the way it will run: real PDFs (generated by the
 * corpus in src/tests/form-detect-fixtures.ts) through pdf.js's legacy build, which is
 * the browser's parser with the polyfills Node lacks. Nothing here is
 * mocked: the composed chain at the bottom goes detect -> name -> validate
 * -> createFormFields -> read back by pdf.js, and asserts where the reader
 * gets each widget.
 */

const byId = (id: string): DetectCase => {
  const c = DETECT_CASES.find((x) => x.id === id);
  if (!c) throw new Error(`no case ${id}`);
  return c;
};

type Matrix = [number, number, number, number, number, number];

async function openPdfjs(bytes: Uint8Array) {
  const pdfjs =
    (await import("pdfjs-dist/legacy/build/pdf.mjs")) as unknown as typeof import("pdfjs-dist");
  const task = pdfjs.getDocument({
    data: bytes.slice(),
    ...PDFJS_DOCUMENT_DEFAULTS,
  });
  return { doc: await task.promise, task };
}

