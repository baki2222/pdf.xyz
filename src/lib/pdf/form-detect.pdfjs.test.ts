const SQUARES = [500, 480, 460, 440].map((y) => ({ x: 72, y, s: 12 }));
const DRAWN: Record<
  string,
  {
    lines: { page: number; y: number; x0: number; x1: number }[];
    squares: { page: number; x: number; y: number; s: number }[];
  }
> = {
  P1a: { lines: [{ ...RUN_SPAN(700), page: 1 }], squares: [] },
  P4: { lines: [{ page: 1, y: 600, x0: 130, x1: 330 }], squares: [] },
  P7: { lines: [], squares: SQUARES.map((q) => ({ ...q, page: 1 })) },
  P10: {
    lines: [
      { ...RUN_SPAN(700), page: 1 },
      { ...RUN_SPAN(700), page: 2 },
    ],
    squares: SQUARES.map((q) => ({ ...q, page: 2 })),
  },
};

async function chain(bytes: Uint8Array, extraReserved: string[] = []) {
  const report = await detectFormFields(bytes, { loadReader: legacyPdfjs });
  const proposals = report.pages.flatMap((p) =>
    p.outcome === "found" ? p.proposals : [],
  );
  const context = await readFormContext(bytes);
  const reserved = [...context.existingNames, ...extraReserved];
  const specs = proposalToDraftFields(proposals, reserved);
  const errors = validateFormFields(specs, context.pageSizes, reserved);
  return { proposals, specs, errors };
}

describe("composed chain: detect -> name -> validate -> createFormFields -> pdf.js", () => {
  for (const id of Object.keys(DRAWN)) {
    it(`${id}: every widget the reader gets sits on what was drawn`, async () => {
      const bytes = await byId(id).build();
      const { proposals, specs, errors } = await chain(bytes);
      const drawn = DRAWN[id]!;
      // Health: one proposal per drawn line and square.
      expect(proposals).toHaveLength(drawn.lines.length + drawn.squares.length);
      expect(errors).toEqual([]);
      const widgets = await readWidgets(
        (await createFormFields(bytes, specs)).bytes,
      );
      expect(widgets.map((w) => w.name).sort()).toEqual(
        specs.map((s) => s.name).sort(),
      );
      for (const spec of specs) {
        const w = widgets.find((x) => x.name === spec.name)!;
        // The card box the builder was handed is the box the reader shows.
        expect(Math.abs(w.card.x - spec.x)).toBeLessThanOrEqual(1);
        expect(Math.abs(w.card.y - spec.y)).toBeLessThanOrEqual(1);
        expect(Math.abs(w.card.width - spec.width)).toBeLessThanOrEqual(1);
        expect(Math.abs(w.card.height - spec.height)).toBeLessThanOrEqual(1);
        const [x0, y0, x1, y1] = w.rect;
        if (spec.type === "text") {
          const line = drawn.lines.find(
            (l) => l.page === w.page && Math.abs(Math.min(y0, y1) - l.y) <= 3,
          );
          expect(line, `no drawn line under ${spec.name}`).toBeDefined();
          const cover =
            Math.max(
              0,
              Math.min(Math.max(x0, x1), line!.x1) -
                Math.max(Math.min(x0, x1), line!.x0),
            ) /
            (line!.x1 - line!.x0);
          expect(cover).toBeGreaterThanOrEqual(0.9);
        } else {
          const sq = drawn.squares.find(
            (q) =>
              q.page === w.page &&
              Math.min(x0, x1) >= q.x - 0.5 &&
              Math.max(x0, x1) <= q.x + q.s + 0.5 &&
              Math.min(y0, y1) >= q.y - 0.5 &&
              Math.max(y0, y1) <= q.y + q.s + 0.5,
          );
          expect(sq, `${spec.name} is not inside a drawn square`).toBeDefined();
        }
      }
    }, 60_000);
  }

  it("a label with a period, in a PDF that has 'mr' and 'name.first': names pass the engine", async () => {
    const d = await PDFDocument.create();
    const page = d.addPage([612, 792]);
    const f = await d.embedFont(StandardFonts.Helvetica);
    page.drawText("Mr. Name: ____________", {
      x: 72,
      y: 700,
      size: 12,
      font: f,
      color: rgb(0, 0, 0),
    });
    page.drawText("Name: ____________", {
      x: 72,
      y: 600,
      size: 12,
      font: f,
      color: rgb(0, 0, 0),
    });
    const form = d.getForm();
    form
      .createTextField("mr")
      .addToPage(page, { x: 400, y: 100, width: 100, height: 18 });
    form
      .createTextField("name.first")
      .addToPage(page, { x: 400, y: 50, width: 100, height: 18 });
    const bytes = await d.save();
    const { proposals, specs, errors } = await chain(bytes);
    expect(proposals.map((p) => p.label).sort()).toEqual(["Mr. Name", "Name"]);
    expect(specs.map((s) => s.name).sort()).toEqual(["mr_name", "name_2"]);
    expect(specs.every((s) => !s.name.includes("."))).toBe(true);
    expect(errors).toEqual([]);
    const widgets = await readWidgets(
      (await createFormFields(bytes, specs)).bytes,
    );
    expect(widgets.map((w) => w.name).sort()).toEqual([
      "mr",
      "mr_name",
      "name.first",
      "name_2",
    ]);
  }, 60_000);

  it("N17: the naming case's taken names give name_2", async () => {
    const c = byId("N17");
    const { specs, errors } = await chain(await c.build(), c.existingNames);
    expect(specs.map((s) => s.name)).toEqual(["name_2"]);
    expect(errors).toEqual([]);
  });

  it("P14: the accented label's name", async () => {
    const { specs } = await chain(await byId("P14").build());
    expect(specs.map((s) => s.name)).toEqual(["prenom"]);
  });

  // Every expectation that names its field is held here, so `name` in the
  // corpus is a check and not a note (review round 3, finding 8's P32 names
  // its three Address lines apart).
  it("every name the corpus expects is the name the chain gives", async () => {
    const named = DETECT_CASES.filter(
      (c) => c.expect !== "none" && c.expect.some((e) => e.name),
    );
    expect(named.map((c) => c.id)).toEqual(
      expect.arrayContaining(["P14", "N17", "P32"]),
    );
    for (const c of named) {
      const { proposals, specs } = await chain(
        await c.build(),
        c.existingNames,
      );
      for (const e of c.expect as Expect[]) {
        if (!e.name) continue;
        const i = proposals.findIndex((p) => matches(p, e));
        expect(i, `${c.id}: ${e.label} not proposed`).toBeGreaterThanOrEqual(0);
        expect(specs[i]!.name, `${c.id}: ${e.label}`).toBe(e.name);
      }
    }
  }, 60_000);
});

