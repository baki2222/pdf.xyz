/**
 * Build the home desk's sample PDF, and write it into the app as bytes.
 *
 *   pnpm exec tsx scripts/build-sample-pdf.ts
 *
 * The sample is three pages made with the same engine the tools use — text
 * on the first two, a form with two empty text fields on the third — so the
 * ticket has real facts to measure and say: pages counted, fields found.
 *
 * WHY BYTES IN THE APP, NOT BUILT IN THE TAB (the redesign planned the tab,
 * WP-05). Built in the tab, the sample's chunk needed pdf-lib's helpers and
 * the font chooser, and the chooser reaches the engine's page-copy code; the
 * build then moved those modules — shared with every tool page's first load —
 * into chunks of their own, and every tool page grew 0.9 KB gzip (measured
 * 2026-10-10, 21 → 23 chunks) for a button on the home page. Shipped as bytes,
 * the button's chunk is the file and nothing else, and a click opens it at
 * once. It is still made here, with pdf-lib and through the chooser
 * (`text-drawing-call-sites.test.ts`'s rule, kept although this script is not
 * shipped), and `src/lib/intent/sample-pdf.test.ts` rebuilds it and requires
 * the shipped bytes to be exactly these, so the two cannot drift.
 *
 * Deterministic: fixed dates, no generated ids — the same input, the same
 * bytes, on any machine.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { PDFDocument, rgb } from "pdf-lib";
import {
  assertFormFieldTextDrawable,
  embedDrawingFont,
  formTextsDrawnOnRegeneration,
} from "@/lib/pdf/unicode-font";
import {
  SAMPLE_FIELDS,
  SAMPLE_PAGES,
  SAMPLE_TITLE,
} from "@/lib/intent/sample-pdf";

/** When the sample was last regenerated; the bytes carry no other date. */
const MADE = new Date("2026-10-10T00:00:00Z");
const SIZE: [number, number] = [612, 792];

/** Each page's lines, top to bottom. */
function linesFor(page: number): string[] {
  const head = `pdf.xyz sample · page ${page} of ${SAMPLE_PAGES}`;
  switch (page) {
    case 1:
      return [
        head,
        "A sample document",
        "A file from pdf.xyz, so the tools have something to work on",
        "before you bring your own. Every word on this page is real text.",
      ];
    case 2:
      return [
        head,
        "A second page of text",
        "Merge it, split it, rotate it, number it or sign it.",
      ];
    default:
      return [head, "A form with two fields", "Fill them in with Fill forms."];
  }
}

export async function buildSamplePdfBytes(): Promise<Uint8Array> {
  const lib = await import("pdf-lib");
  const doc = await PDFDocument.create({ updateMetadata: false });
  doc.setTitle(SAMPLE_TITLE);
  doc.setProducer("pdf.xyz");
  doc.setCreator("pdf.xyz");
  doc.setCreationDate(MADE);
  doc.setModificationDate(MADE);

  const pages = Array.from({ length: SAMPLE_PAGES }, (_, i) => linesFor(i + 1));
  const labels = SAMPLE_FIELDS.map((field) => field.label);
  const font = await embedDrawingFont(doc, [...pages.flat(), ...labels]);
  const ink = rgb(0.08, 0.1, 0.13);
  const muted = rgb(0.38, 0.42, 0.47);

  pages.forEach((lines, i) => {
    const page = doc.addPage(SIZE);
    const [head, title, ...body] = lines as [string, string, ...string[]];
    page.drawText(head, { x: 72, y: 720, size: 9, font, color: muted });
    page.drawText(title, { x: 72, y: 672, size: 24, font, color: ink });
    body.forEach((line, n) =>
      page.drawText(line, {
        x: 72,
        y: 632 - n * 18,
        size: 12,
        font,
        color: ink,
      }),
    );
    if (i === SAMPLE_PAGES - 1) {
      const form = doc.getForm();
      SAMPLE_FIELDS.forEach((spec, n) => {
        const y = 560 - n * 56;
        page.drawText(spec.label, {
          x: 72,
          y: y + 30,
          size: 10,
          font,
          color: muted,
        });
        form.createTextField(spec.name).addToPage(page, {
          x: 72,
          y,
          width: 280,
          height: 24,
        });
      });
    }
  });

  // `save()` draws every field's appearance with the form's own font, like
  // every AcroForm writer in the app; the same check guards it (the fields
  // are empty, so it has nothing to refuse — and would say so if it did).
  assertFormFieldTextDrawable(
    formTextsDrawnOnRegeneration(doc.getForm().getFields(), lib),
  );
  return doc.save();
}

/** The module the app imports: the bytes, base64, in lines a diff can show. */
export function bytesModule(bytes: Uint8Array): string {
  const b64 = Buffer.from(bytes).toString("base64");
  const lines = b64.match(/.{1,76}/g) ?? [];
  return [
    "/**",
    " * The home desk's sample PDF, as bytes. GENERATED by",
    " * `scripts/build-sample-pdf.ts` — do not edit; rerun it.",
    " * `sample-pdf.test.ts` requires these to be exactly what it builds.",
    " */",
    "export const SAMPLE_PDF_BASE64 = [",
    ...lines.map((line) => `  "${line}",`),
    '].join("");',
    "",
  ].join("\n");
}

export const BYTES_MODULE = path.join(
  process.cwd(),
  "src",
  "lib",
  "intent",
  "sample-pdf-bytes.ts",
);

if (
  process.argv[1]?.replace(/\\/g, "/").endsWith("scripts/build-sample-pdf.ts")
) {
  buildSamplePdfBytes()
    .then((bytes) => {
      writeFileSync(BYTES_MODULE, bytesModule(bytes));
      console.log(
        `build-sample-pdf: ${bytes.byteLength} bytes -> ${path.relative(process.cwd(), BYTES_MODULE)}`,
      );
    })
    .catch((error: unknown) => {
      console.error(error);
      process.exit(1);
    });
}
