/**
 * Regenerate `src/lib/pdf/font-coverage.generated.ts` from the installed Noto
 * TTFs.
 *
 * Run it after changing `FONT_PACKS` or bumping a font package:
 *
 *     pnpm fonts:coverage
 *
 * Nothing in the app calls this at runtime. `font-coverage.test.ts` re-derives
 * the same table from the same files and fails when the checked-in copy has
 * drifted, so a font bump cannot leave the router pointing at a face that no
 * longer has the glyphs — which would show up as an extra download at best and
 * a refusal for text we can actually draw at worst.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { FONT_PACKS } from "../src/lib/pdf/font-packs";
import { encodeCoverage } from "../src/lib/pdf/coverage-bitmap";
import {
  notoCharacterSet,
  installedPackageVersion,
} from "../src/lib/pdf/noto-source";

const OUT = path.join(
  process.cwd(),
  "src",
  "lib",
  "pdf",
  "font-coverage.generated.ts",
);

async function main() {
  const entries: string[] = [];
  for (const pack of FONT_PACKS) {
    const installed = installedPackageVersion(pack);
    if (installed !== pack.version) {
      console.error(
        `generate-font-coverage: ${pack.pkg} is installed at ${installed} but ` +
          `FONT_PACKS says ${pack.version}. Update font-packs.ts first — the ` +
          `version is stamped into the served URL.`,
      );
      process.exit(1);
    }
    const cps = await notoCharacterSet(pack);
    if (cps.size < 100) {
      console.error(
        `generate-font-coverage: ${pack.id} reports only ${cps.size} code ` +
          `points. A near-empty cmap would refuse almost every string while ` +
          `looking like a valid table.`,
      );
      process.exit(1);
    }
    const coverage = encodeCoverage(cps);
    entries.push(
      `  ${pack.id}: {\n    bmp: "${coverage.bmp}",\n    astral: ${JSON.stringify(coverage.astral)},\n  },`,
    );
    console.log(`generate-font-coverage: ${pack.id} ${cps.size} code points`);
  }

  const source = `/**
 * GENERATED by \`pnpm fonts:coverage\` — do not edit.
 *
 * One bitmap per shipped face, derived from that TTF's own cmap. Imported
 * dynamically (see \`font-coverage.ts\`) so a page that never draws a non-WinAnsi
 * character never downloads it.
 *
 * \`font-coverage.test.ts\` regenerates this from the installed packages and
 * fails on any difference.
 */
import type { FontPackId } from "./font-packs";
import type { PackCoverage } from "./coverage-bitmap";

export const FONT_COVERAGE: Record<FontPackId, PackCoverage> = {
${entries.join("\n")}
};
`;
  writeFileSync(OUT, source, "utf8");
  console.log(`generate-font-coverage: wrote ${OUT}`);
}

main().catch((error) => {
  console.error("generate-font-coverage failed:", error);
  process.exit(1);
});
