/**
 * Write `src/lib/pdf/handwriting-coverage.generated.ts`: for each handwriting
 * face of a typed signature, the code points its own cmap maps, as sorted
 * inclusive ranges.
 *
 *   pnpm fonts:handwriting
 *
 * Derived, never typed: `handwriting.test.ts` calls
 * {@link handwritingCoverage} on the installed TTFs and fails when the
 * committed table differs, so a font bump that drops a letter cannot leave the
 * panel promising it.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { HANDWRITING_FACE_LIST } from "../src/lib/pdf/handwriting";
import {
  installedPackageVersion,
  notoCharacterSet,
} from "../src/lib/pdf/noto-source";

export type CoverageRanges = readonly (readonly [number, number])[];

/** Collapse a set of code points into sorted, inclusive, maximal ranges. */
export function toRanges(codePoints: Iterable<number>): [number, number][] {
  const sorted = [...new Set(codePoints)].sort((a, b) => a - b);
  const out: [number, number][] = [];
  for (const cp of sorted) {
    const last = out[out.length - 1];
    if (last && last[1] === cp - 1) last[1] = cp;
    else out.push([cp, cp]);
  }
  return out;
}

/** Each face's ranges, read from the installed TTF. Throws on drift. */
export async function handwritingCoverage(): Promise<
  Record<string, [number, number][]>
> {
  const out: Record<string, [number, number][]> = {};
  for (const face of HANDWRITING_FACE_LIST) {
    const installed = installedPackageVersion(face);
    if (installed !== face.version) {
      throw new Error(
        `${face.pkg} is installed at ${installed} but handwriting.ts says ${face.version}`,
      );
    }
    const cps = await notoCharacterSet(face);
    // A handwriting face with fewer letters than basic Latin is a broken
    // file, not a narrow one; a near-empty table would send every name to
    // the fallback while looking valid.
    if (cps.size < 95) {
      throw new Error(`${face.id} reports only ${cps.size} code points`);
    }
    out[face.id] = toRanges(cps);
  }
  return out;
}

const isMain =
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(process.argv[1]).href;

if (isMain) {
  void handwritingCoverage()
    .then((coverage) => {
      const body = Object.entries(coverage)
        .map(
          ([id, ranges]) =>
            `  ${JSON.stringify(id)}: [\n${ranges.map(([a, b]) => `    [0x${a.toString(16)}, 0x${b.toString(16)}],`).join("\n")}\n  ],`,
        )
        .join("\n");
      const source = `/**
 * GENERATED by \`pnpm fonts:handwriting\` (scripts/generate-handwriting-coverage.ts)
 * — do not edit.
 *
 * The code points each handwriting face's own cmap maps, as sorted inclusive
 * ranges. \`handwriting.test.ts\` re-derives them from the installed TTFs and
 * fails on any difference.
 */
import type { HandwritingStyle } from "./offered-kinds";

export const HANDWRITING_COVERAGE: Record<
  HandwritingStyle,
  readonly (readonly [number, number])[]
> = {
${body}
};
`;
      const out = path.join(
        process.cwd(),
        "src",
        "lib",
        "pdf",
        "handwriting-coverage.generated.ts",
      );
      writeFileSync(out, source, "utf8");
      console.log(`generate-handwriting-coverage: wrote ${out}`);
    })
    .catch((error: unknown) => {
      console.error(
        `generate-handwriting-coverage: ${(error as Error).message}`,
      );
      process.exit(1);
    });
}
